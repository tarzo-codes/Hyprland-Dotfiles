window.text.color=$FG
base.color=$SUR
alt.base.color=$SUR
text.color=$FG
highlight.color=$ACC
highlight.text.color=#FFFFFF
button.color=$SUR
button.text.color=$FG
tooltip.color=$SUR
tooltip.text.color=$FG
inactive.window.color=$BG
inactive.text.color=$FG
EOF

mv -f "$KV_TMP" "$KVANTUM_DIR/FluxDots.kvconfig"



